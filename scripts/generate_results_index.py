#!/usr/bin/env python3
"""Generate results/INDEX.md from results/index.yaml.

The YAML file is the detailed source of truth.  This script deliberately emits
a concise catalogue: readers can scan evidence status here and follow a bundle
link for the full caveats recorded in YAML and the bundle README.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from pathlib import Path

import yaml


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
SOURCE = RESULTS / "index.yaml"
OUTPUT = RESULTS / "INDEX.md"


def compact(value: object) -> str:
    """Collapse YAML prose to one Markdown-table-safe line."""
    if value is None:
        return "—"
    return re.sub(r"\s+", " ", str(value)).strip().replace("|", "\\|")


def status_family(status: str) -> str:
    if status.startswith("VOID-"):
        return "VOID"
    if status.startswith("SUPERSEDED-BY-"):
        return "SUPERSEDED"
    return status


def gate_label(entry: dict) -> str:
    gate = entry.get("fabric_gate", "ABSENT")
    if gate == "PRESENT-PASS":
        return "`PRESENT-PASS`"
    if entry.get("description", "").lower().startswith("official") or (
        entry.get("dir") == "20260826-nccl-controlled"
    ):
        return "direct measurement"
    return f"`{gate}`"


def bundle_link(entry: dict) -> str:
    name = entry["dir"]
    return f"[{name}]({name}/)"


def render_table(entries: list[dict]) -> list[str]:
    lines = [
        "| Bundle | Date | Nodes / TP | Gate | Description |",
        "|---|---|---|---|---|",
    ]
    for entry in entries:
        nodes = compact(entry.get("nodes"))
        tp = compact(entry.get("tp_size"))
        lines.append(
            f"| {bundle_link(entry)} | {compact(entry.get('date'))} | "
            f"{nodes} / {tp} | {gate_label(entry)} | "
            f"{compact(entry.get('description'))} |"
        )
    return lines


def render(data: dict) -> str:
    entries = data["directories"]
    families = Counter(status_family(str(entry["status"])) for entry in entries)
    gates = Counter(str(entry.get("fabric_gate", "ABSENT")) for entry in entries)

    current = [entry for entry in entries if entry["status"] == "CURRENT"]
    replaced = [
        entry
        for entry in entries
        if str(entry["status"]).startswith("SUPERSEDED-BY-")
    ]
    void = [entry for entry in entries if str(entry["status"]).startswith("VOID-")]

    lines = [
        "# Provenance index",
        "",
        "<!-- Generated by scripts/generate_results_index.py; edit index.yaml instead. -->",
        "",
        "[`index.yaml`](index.yaml) is the machine-readable source of truth. It records",
        "the full per-bundle audit: node and TP evidence, harness, requested and actual",
        "output tokens, repetitions, gate artifacts, raw files, caveats, void reasons,",
        "and diagnostic baseline values.",
        "",
        "## Audit summary",
        "",
        "| Item | Count |",
        "|---|---:|",
        f"| Result bundles | {len(entries)} |",
        f"| `CURRENT` | {families['CURRENT']} |",
        f"| `VOID` | {families['VOID']} |",
        f"| `SUPERSEDED` | {families['SUPERSEDED']} |",
        f"| Own passing fabric gate | {gates['PRESENT-PASS']} |",
        f"| Gate absent | {gates['ABSENT']} |",
        f"| Predates the gate | {gates['PRE-DATES-GATE']} |",
        "",
        "`CURRENT` means useful within the caveats recorded for that bundle. An absent",
        "fabric gate weakens performance evidence but does not invalidate pass/fail",
        "quality evidence or a methodology-only control.",
        "",
        "## Current evidence",
        "",
        *render_table(current),
        "",
        "## Superseded evidence",
        "",
        *render_table(replaced),
        "",
        "## Void evidence retained as diagnostic baselines",
        "",
        *render_table(void),
        "",
        "VOID bundles remain committed because their values fingerprint known failures.",
        "They must not be cited as current performance.",
        "",
        "## Rules for citations",
        "",
        "1. Link to committed raw data or a result bundle, not only a prose summary.",
        "2. State nodes/TP, prompt, harness, actual output window, warm/cold state,",
        "   repetitions, statistic, and gate status.",
        "3. Do not compare across prompts, harness definitions, or output windows.",
        "4. Cite `VOID` magnitudes only as named failure signatures.",
        "5. Regenerate this page after changing `index.yaml` and run the index tests.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if results/INDEX.md is not the generated output",
    )
    args = parser.parse_args()

    data = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    generated = render(data)

    if args.check:
        existing = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if existing != generated:
            print(
                "results/INDEX.md is stale; run scripts/generate_results_index.py",
                file=sys.stderr,
            )
            return 1
        return 0

    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
